def extract(text, name):
    tokens = r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*[\s\S]*?\*/|//[^\n]*'
    masked = re.sub(tokens, lambda m: ' ' * len(m.group()), text)
    matches = list(re.finditer(r'(?:static\s+)?(?:inline\s+)?(?:int|void)\s+\b'
                              + re.escape(name) + r'\s*\([^;{}]*\)\s*\{', masked))
    if len(matches) != 1:
        raise ValueError('Missing/ambiguous NOR admission body: ' + name)
    start = matches[0].start()
    opening = masked.index('{', start)
    depth = 0
    for match in re.finditer('[{}]', masked[opening:]):
        depth += 1 if match.group() == '{' else -1
        if depth == 0:
            return text[start:opening + match.end()]
    raise ValueError('Unterminated NOR admission body: ' + name)


def actual_functions(texts):
    if set(texts) != set(SOURCE_PATHS):
        raise ValueError('Exact NOR admission inputs required')
    return {name: {'source_key': key, 'body': extract(texts[key], name)}
            for key, names in FUNCTIONS.items() for name in names}


def _define(text, name):
    values = re.findall(r'^#define[ \t]+' + re.escape(name) + r'[ \t]+([^\n]+)', text, re.M)
    if len(values) != 1:
        raise ValueError('Missing/ambiguous NOR admission macro: ' + name)
    return re.sub(r'/\*.*?\*/', '', values[0]).strip()


MACROS = {'SPINOR_OP_RDSR': '0x05', 'SPINOR_OP_RDFSR': '0x70',
          'SPINOR_OP_WREN': '0x06', 'SPINOR_OP_WRDI': '0x04',
          'SPINOR_OP_CHIP_ERASE': '0xc7', 'SR_WIP': 'BIT(0)',
          'FSR_READY': 'BIT(7)'}


def validate_inputs(texts):
    actual_functions(texts)
    if _define(texts['nor'], 'DEFAULT_READY_WAIT_JIFFIES') != '(40UL * HZ)':
        raise ValueError('NOR admission ready deadline changed')
    for name, value in MACROS.items():
        if _define(texts['header'], name) != value:
            raise ValueError('NOR admission macro changed: ' + name)
    enum = re.findall(r'enum spi_nor_ops\s*\{([^{}]+)\}', texts['header'])
    if len(enum) != 1 or re.sub(r'\s+', '', enum[0]) != (
        'SPI_NOR_OPS_READ=0,SPI_NOR_OPS_WRITE,SPI_NOR_OPS_ERASE,'
        'SPI_NOR_OPS_LOCK,SPI_NOR_OPS_UNLOCK,'):
        raise ValueError('NOR operation enum changed')
    flags = re.findall(r'enum spi_nor_option_flags\s*\{([^{}]+)\}', texts['header'])
    if len(flags) != 1 or re.sub(r'\s+', '', flags[0]) != 'SNOR_F_USE_FSR=BIT(0),':
        raise ValueError('NOR FSR flag changed')


